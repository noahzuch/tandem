// Static HTML report: summary tables + the 4 edits side by side per format.
import type { Summary } from '../scripts/compare.ts'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function patchHtml(patch: string): string {
  return patch
    .split('\n')
    .slice(2)
    .map((l) => {
      const cls = l.startsWith('+') ? 'add' : l.startsWith('-') ? 'del' : l.startsWith('@@') ? 'hunk' : ''
      return `<span class="${cls}">${esc(l)}</span>`
    })
    .join('\n')
}

const LABEL: Record<string, string> = { html: 'A · HTML', json: 'B · PM JSON (getJSON)', 'json-min': 'B-min · PM JSON, defaults stripped' }

export function renderReport(s: Summary): string {
  const formats = ['html', 'json', 'json-min'] as const
  const editRows = s.edits
    .map(
      (e) => `<tr><td>${esc(e.title)}</td>${formats
        .map((f) => {
          const v = e.perFormat[f]
          return `<td class="num">${v.edit.emitChars} / ${v.edit.emitTokens}</td><td class="num">+${v.diff.added} −${v.diff.removed}</td>`
        })
        .join('')}<td class="num">${e.yjs.incrementalUpdateBytes} B</td></tr>`,
    )
    .join('')
  const sections = s.edits
    .map(
      (e) => `<section><h2>${esc(e.title)}</h2>
<p class="meta">HTML: next editor save changes +${e.htmlSaveChurn.added}/−${e.htmlSaveChurn.removed} lines (formatting); document stable: ${e.htmlStableAfterSave}.
Yjs: incremental update ${e.yjs.incrementalUpdateBytes} B vs. naive full replace ${e.yjs.fullReplaceUpdateBytes} B.</p>
<div class="grid">${formats
        .map((f) => {
          const v = e.perFormat[f]
          return `<div class="col"><h3>${LABEL[f]}</h3>
<p class="meta">${v.edit.calls} edit call(s), agent emits ${v.edit.emitChars} chars (~${v.edit.emitTokens} tokens) · brackets ${v.prone.brackets} · depth ${v.prone.depth} · escapes ${v.prone.escapes} · tags ${v.prone.tags}</p>
<details open><summary>what the agent writes (new_string)</summary><pre>${esc(v.edit.new)}</pre></details>
<details><summary>unified diff (+${v.diff.added} −${v.diff.removed}, ${v.diff.chars} chars)</summary><pre>${patchHtml(v.diff.patch)}</pre></details>
</div>`
        })
        .join('')}</div></section>`,
    )
    .join('\n')
  const kv = (o: Record<string, unknown>, fmt: (v: any) => string) =>
    Object.entries(o)
      .map(([k, v]) => `<tr><td>${esc(k)}</td><td class="num">${fmt(v)}</td></tr>`)
      .join('')
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Storage format comparison</title>
<style>
:root { --bg:#fbfbfa; --fg:#1d1d1d; --muted:#666; --line:#ddd; --add:#e3f5e1; --del:#fde8e8; --card:#fff; --hunk:#4a78c2; }
@media (prefers-color-scheme: dark) { :root { --bg:#17181a; --fg:#e8e8e8; --muted:#9a9a9a; --line:#333; --add:#1d3a1f; --del:#47201f; --card:#1f2023; --hunk:#8fb0e8; } }
body { background:var(--bg); color:var(--fg); font:14px/1.5 system-ui, sans-serif; margin:0 auto; padding:16px; max-width:1500px; }
table { border-collapse:collapse; margin:8px 0 20px; } td,th { border:1px solid var(--line); padding:4px 8px; text-align:left; }
.num { text-align:right; font-variant-numeric:tabular-nums; }
.grid { display:grid; grid-template-columns:repeat(auto-fit, minmax(340px, 1fr)); gap:12px; }
.col { background:var(--card); border:1px solid var(--line); border-radius:6px; padding:8px 10px; min-width:0; }
pre { overflow:auto; max-height:420px; font:12px/1.4 ui-monospace, monospace; margin:4px 0; }
.add { background:var(--add); display:block; } .del { background:var(--del); display:block; } .hunk { color:var(--hunk); display:block; }
.meta { color:var(--muted); font-size:12px; margin:2px 0 6px; } h3 { margin:4px 0; font-size:14px; }
</style></head><body>
<h1>What lives on disk? HTML vs ProseMirror JSON vs Yjs</h1>
<p class="meta">Sample ${esc(s.sample)} · generated by <code>npm run compare</code>. Files: <code>out/edits/&lt;edit&gt;/</code>. Tokens: cl100k proxy.</p>
<h2>Agent edits: emitted chars / ~tokens and diff lines</h2>
<table><tr><th>edit</th>${formats.map((f) => `<th colspan="2">${LABEL[f]}</th>`).join('')}<th>Yjs update</th></tr>${editRows}</table>
<h2>Size, speed</h2>
<table><tr><th>format</th><th>bytes / gzip</th></tr>${kv(s.sizes, (v) => `${v.bytes} / ${v.gzip}`)}</table>
<table><tr><th>format</th><th>prose share of file</th></tr>${kv(s.signalRatio, (v) => `${(v * 100).toFixed(0)}%`)}</table>
<table><tr><th>format</th><th>load / save (median ms)</th></tr>${kv(s.speedMs, (v) => `${v.load.toFixed(2)} / ${v.save.toFixed(2)}`)}</table>
<p>Yjs state ${s.yjsGrowth.initial} B → ${s.yjsGrowth.gcOn} B (gc on) / ${s.yjsGrowth.gcOff} B (gc off) after typing and deleting ${s.yjsGrowth.typedChars} chars.</p>
<h2>Agent mistakes: what feedback does the agent get?</h2>
<table><tr><th>mistake</th><th>B: JSON.parse</th><th>B: JSON Schema (ajv)</th><th>B: ProseMirror check()</th><th>A: collab check (HTML)</th></tr>
${s.mistakes.map((m) => `<tr><td>${esc(m.what)}</td><td>${esc(m.json.parse)}</td><td>${esc(m.json.jsonSchema)}</td><td>${esc(m.json.prosemirror)}</td><td>${esc(m.html.worst)}</td></tr>`).join('')}</table>
<h2>Agent edits the file while the user types (Yjs)</h2>
<table><tr><th>scenario</th><th>strategy</th><th>user edit synced first</th><th>converged</th><th>agent edit</th><th>user edit</th><th>note</th></tr>
${s.yjsScenarios.map((r) => `<tr><td>${r.id}</td><td>${r.strategy}</td><td>${r.userEditReachedServerFirst}</td><td>${r.converged}</td><td>${r.agentEditSurvived ? 'kept' : '<b>LOST</b>'}</td><td>${r.userEditSurvived ? 'kept' : '<b>LOST</b>'}</td><td>${esc(r.note)}</td></tr>`).join('')}</table>
${sections}
</body></html>
`
}
